def fetch(url):
    req = urllib.request.Request(url, headers={"User-Agent": "tokenstep-gen-pricing"})
    with urllib.request.urlopen(req, timeout=60) as resp:
        return json.loads(resp.read().decode("utf-8"))


def slim(snapshot):
    models = {}
    for model_id, entry in sorted(snapshot.items()):
        if not isinstance(entry, dict):
            continue
        low = model_id.lower()
        canon = None
        for kw, name in KEYWORDS:
            if kw in low:
                canon = name
                break
        if canon is None:
            continue
        inp = entry.get("input_cost_per_token")
        out = entry.get("output_cost_per_token")
        crd = entry.get("cache_read_input_token_cost")
        cwr = entry.get("cache_creation_input_token_cost")
        if inp is None and out is None:
            continue  # no usable rates
        rate = {}
        if inp is not None:
            rate["input_usd_per_1m"] = round(inp * 1_000_000, 4)
        if out is not None:
            rate["output_usd_per_1m"] = round(out * 1_000_000, 4)
        if crd is not None:
            rate["cache_read_usd_per_1m"] = round(crd * 1_000_000, 4)
        if cwr is not None:
            rate["cache_creation_usd_per_1m"] = round(cwr * 1_000_000, 4)
        # first (most specific) id wins per canonical name
        if canon not in models:
            models[canon] = rate
    return models


def main():
    if len(sys.argv) > 1:
        snapshot = json.loads(open(sys.argv[1], encoding="utf-8").read())
        src = sys.argv[1]
    else:
        print("fetching", SOURCE)
        snapshot = fetch(SOURCE)
        src = SOURCE
    models = slim(snapshot)
    out = {
        "notes": ("Generated by tools/gen-pricing.py from the LiteLLM public "
                  f"dataset ({src}). Rough local estimates only — not a bill. "
                  "Regenerate instead of hand-editing."),
        "default_total_usd_per_1m": 1.0,
        "tools": {
            "Codex": {"total_usd_per_1m": 1.0},
            "Claude Code": {"total_usd_per_1m": 3.0},
        },
        "models": models,
    }
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(out, fh, ensure_ascii=False, indent=2)
        fh.write("\n")
    print(f"wrote {OUT}: {len(models)} models")


if __name__ == "__main__":
    main()
